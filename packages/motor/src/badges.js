export function getBadges(history) {
  const { flight, onTimeOnce, quotas, overdue, hives, earlyMornings } = history;
  const { marks } = flight;

  const stateById = {
    "primera-celda": { current: history.cells, earnedOn: marks.firstCell ?? null },
    "panal-cerrado": { current: flight.closedDays, earnedOn: marks.firstClose ?? null },
    "semana-de-vuelo": { current: flight.best, earnedOn: marks.streak7 ?? null },
    "luna-de-miel": { current: flight.best, earnedOn: marks.streak30 ?? null },
    "cien-flores": { current: flight.best, earnedOn: marks.streak100 ?? null },
    "vuelta-al-panal": { current: flight.comebacks, earnedOn: marks.comeback ?? null },
    "nectar-fresco": { current: onTimeOnce.count, earnedOn: onTimeOnce.tenthOn },
    "ronda-firme": { current: quotas.best, earnedOn: quotas.fourthOn },
    "panal-limpio": {
      current: overdue.filled > 0 && overdue.pending === 0 ? 1 : 0,
      earnedOn: overdue.pending === 0 ? overdue.lastOn : null,
    },
    "colmena-fundada": { current: hives.foundedWithTeam, earnedOn: null },
    "entrada-abierta": { current: hives.joinedCount, earnedOn: null },
    "primer-cuadro": { current: hives.bestFrame, earnedOn: hives.firstFrameOn },
    enjambrazon: { current: hives.closedCount, earnedOn: hives.closedOn },
    "ala-amiga": { current: 0, earnedOn: null },
    madrugadora: { current: earlyMornings.days, earnedOn: earlyMornings.fifthOn },
    "flor-de-siete": { current: flight.bestConsecutiveClosed, earnedOn: marks.sevenClosed ?? null },
    polinizadora: { current: 0, earnedOn: null },
  };

  return BADGES.map((badge) => {
    const { current, earnedOn } = stateById[badge.id];
    const earned = badge.available && current >= badge.goal;
    return {
      ...badge,
      current: Math.min(current, badge.goal),
      earned,
      earnedOn: earned ? earnedOn : null,
    };
  });
}
